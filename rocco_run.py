class Player:
    def __init__(self, x, y):
        self.x = float(x)
        self.y = float(y)
        self.w = SMALL_W
        self.h = SMALL_H
        self.vx = 0.0
        self.vy = 0.0
        self.big = False
        self.on_ground = False
        self.facing = 1
        self.coyote = 0.0
        self.jump_buffer = 0.0
        self.jumped = False          # True only on the frame a jump starts
        self.skidding = False
        self.invincible = 0.0
        self.grow_flash = 0.0
        self.stomp_chain = 0
        self.anim = 0.0
        self.prev_bottom = self.y + self.h
        self.visible = True

    @property
    def centerx(self):
        return self.x + self.w / 2

    @property
    def bottom(self):
        return self.y + self.h

    def set_big(self, big):
        """Grow or shrink while keeping the feet and the center in place."""
        if big == self.big:
            return
        bottom = self.bottom
        center = self.centerx
        self.big = big
        self.w, self.h = (BIG_W, BIG_H) if big else (SMALL_W, SMALL_H)
        self.x = center - self.w / 2
        self.y = bottom - self.h
        self.grow_flash = 0.7

    def update(self, dt, ctl, level):
        """Move the hero for one frame. Returns the (col, row) tiles hit by the head."""
        self.jumped = False
        if self.invincible > 0:
            self.invincible -= dt
        if self.grow_flash > 0:
            self.grow_flash -= dt

        # ---------- horizontal movement ----------
        direction = (1 if ctl.right else 0) - (1 if ctl.left else 0)
        limit = RUN_SPEED if ctl.run else WALK_SPEED
        accel = ACCEL if self.on_ground else ACCEL * AIR_CONTROL
        self.skidding = False
        if direction != 0:
            if self.vx * direction < 0:
                # pressing against the current motion: skid / brake
                self.vx += direction * SKID_DECEL * dt
                self.skidding = self.on_ground
                if self.vx * direction > 0:
                    self.vx = min(abs(self.vx), limit) * direction
            elif abs(self.vx) < limit:
                # speed up ONLY while below the limit, then clamp to the limit
                self.vx += direction * accel * dt
                if abs(self.vx) > limit:
                    self.vx = direction * limit
            else:
                # faster than allowed (for example run was released): ease down
                self.vx = approach(self.vx, direction * limit, FRICTION * dt)
            self.facing = direction
        else:
            slow = FRICTION if self.on_ground else AIR_FRICTION
            self.vx = approach(self.vx, 0.0, slow * dt)
        # final safety clamp - can never go faster than RUN_SPEED
        self.vx = clamp(self.vx, -RUN_SPEED, RUN_SPEED)

        # ---------- jumping (with coyote time and jump buffering) ----------
        if ctl.jump_pressed:
            self.jump_buffer = JUMP_BUFFER_TIME
        elif self.jump_buffer > 0:
            self.jump_buffer -= dt
        if self.on_ground:
            self.coyote = COYOTE_TIME
        elif self.coyote > 0:
            self.coyote -= dt
        if self.jump_buffer > 0 and self.coyote > 0:
            speed = JUMP_SPEED
            if abs(self.vx) > WALK_SPEED + 1:
                speed += RUN_JUMP_BONUS
            self.vy = -speed
            self.on_ground = False
            self.coyote = 0.0
            self.jump_buffer = 0.0
            self.jumped = True

        # ---------- gravity (variable jump height) ----------
        # Half of the gravity is added before moving and half after, so the
        # jump height matches the physics formula (v * v / 2g) at any frame rate.
        g = GRAVITY
        if self.vy < 0 and not ctl.jump_held:
            g *= JUMP_RELEASE_GRAVITY      # released early: start falling sooner
        self.vy = min(self.vy + g * dt * 0.5, MAX_FALL_SPEED)

        # ---------- move and collide ----------
        self.prev_bottom = self.bottom
        result = move_and_collide(self, level, dt, finds_hidden=True)
        self.on_ground = result["landed"]
        if not self.on_ground:
            self.vy = min(self.vy + g * dt * 0.5, MAX_FALL_SPEED)
        if self.on_ground:
            self.stomp_chain = 0

        # ---------- animation clock ----------
        if self.on_ground and abs(self.vx) > 5:
            self.anim += abs(self.vx) * dt / 22.0
        return result["head"]

    def pose(self):
        """Pick the drawing pose and the animation frame."""
        if not self.on_ground:
            return ("jump" if self.vy < 0 else "fall"), 0
        if self.skidding:
            return "skid", 0
        if abs(self.vx) > 20:
            return "walk", int(self.anim) % 4
        return "stand", 0


