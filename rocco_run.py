def check_level(name, rows):
    """Look for common mistakes in a level map. Returns a list of warnings.
    Raises ValueError for mistakes that would crash the game."""
    if len(rows) != 15:
        raise ValueError("Level %s must have exactly 15 rows (it has %d)." % (name, len(rows)))
    width = len(rows[0])
    for i, row in enumerate(rows):
        if len(row) != width:
            raise ValueError("Level %s: row %d has %d characters, row 0 has %d."
                             % (name, i, len(row), width))
    warnings = []
    text = "".join(rows)
    for ch in set(text):
        if ch not in TILE_TYPES:
            warnings.append("unknown character '%s' (treated as empty)" % ch)
    for ch in "SFC":
        count = text.count(ch)
        if count != 1:
            warnings.append("needs exactly one '%s' (found %d)" % (ch, count))
    # gaps in the ground (columns with nothing solid in rows 13-14)
    gap = 0
    for c in range(width):
        open_column = rows[13][c] not in SOLID_CHARS and rows[13][c] != "="
        gap = gap + 1 if open_column else 0
        if gap == 4 and name != "1-3":
            warnings.append("ground gap wider than 3 tiles near column %d" % c)
    # pipe heights
    for r in range(15):
        for c in range(width - 1):
            if rows[r][c] == "{":
                h = 1
                while r + h < 15 and rows[r + h][c] == "[":
                    h += 1
                if h > 4:
                    warnings.append("pipe at column %d is %d tiles tall (max 4)" % (c, h))
    # one-way platform widths (sky world rule)
    for r in range(15):
        run = 0
        for c in range(width + 1):
            if c < width and rows[r][c] == "=":
                run += 1
            else:
                if 0 < run < 7 and name == "1-3":
                    warnings.append("cloud in row %d ending at column %d is only %d wide"
                                    % (r, c - 1, run))
                run = 0
    return warnings


