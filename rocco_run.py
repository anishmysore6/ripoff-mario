class Level:
    """Holds the tile grid of one world plus everything spawned from it."""
    def __init__(self, world_index):
        info = WORLDS[world_index]
        self.name = info["name"]
        self.label = info["label"]
        self.theme = info["theme"]
        self.grid = [list(row) for row in info["map"]]
        self.rows = len(self.grid)
        self.cols = len(self.grid[0])
        self.width = self.cols * TILE
        self.coins = []
        self.enemies = []
        self.start = (2 * TILE, 12 * TILE)
        self.flag_col, self.flag_row = self.cols - 10, 12
        self.castle_col, self.castle_row = self.cols - 6, 12
        self.bumps = {}             # (col, row) -> seconds since the block was bumped
        for r in range(self.rows):
            for c in range(self.cols):
                ch = self.grid[r][c]
                if ch not in TILE_TYPES:
                    self.grid[r][c] = "."
                elif ch == "o":
                    self.coins.append(Coin(c, r))
                    self.grid[r][c] = "."
                elif ch in "EX":
                    self.enemies.append(Enemy(c * TILE + (TILE - ENEMY_W) / 2,
                                              (r + 1) * TILE - ENEMY_H, ch))
                    self.grid[r][c] = "."
                elif ch == "S":
                    self.start = (c * TILE + (TILE - SMALL_W) / 2, (r + 1) * TILE - SMALL_H)
                    self.grid[r][c] = "."
                elif ch == "F":
                    self.flag_col, self.flag_row = c, r
                elif ch == "C":
                    self.castle_col, self.castle_row = c, r
                    self.grid[r][c] = "."
        # pipes: (column, top row, height) so each pipe is drawn as one tube
        self.pipes = []
        for r in range(self.rows):
            for c in range(self.cols - 1):
                if self.grid[r][c] == "{":
                    h = 1
                    while r + h < self.rows and self.grid[r + h][c] == "[":
                        h += 1
                    self.pipes.append((c, r, h))
        # flagpole and castle geometry (pixels)
        self.pole_x = self.flag_col * TILE + TILE / 2
        self.pole_bottom = self.flag_row * TILE
        self.pole_top = (self.flag_row - FLAG_POLE_TILES) * TILE
        self.castle_x = self.castle_col * TILE
        self.castle_y = (self.castle_row + 1) * TILE - 5 * TILE
        self.door_x = self.castle_x + 2.5 * TILE

    def tile(self, col, row):
        if row < 0 or row >= self.rows:
            return "."
        if col < 0 or col >= self.cols:
            return "#"               # invisible walls at both ends of the level
        return self.grid[row][col]

    def set_tile(self, col, row, ch):
        if 0 <= row < self.rows and 0 <= col < self.cols:
            self.grid[row][col] = ch

    def is_solid(self, col, row):
        return self.tile(col, row) in SOLID_CHARS

    def can_stand_on(self, col, row):
        ch = self.tile(col, row)
        return ch in SOLID_CHARS or ch == "="


def move_and_collide(body, level, dt, finds_hidden=False):
    """Move any body (player, enemy, mushroom) and resolve tile collisions.

    Order (as required):
      1. move horizontally          2. resolve walls
      3. move vertically            4. resolve floors and ceilings
      5. one-way (cloud) platforms, handled separately
    Tiles the body is already overlapping (for example right after growing)
    are ignored, so a body can never get stuck inside a block.
    """
    result = {"wall": 0, "landed": False, "head": []}

    # ---- 1 + 2: horizontal ----
    old_left = body.x
    old_right = body.x + body.w
    body.x += body.vx * dt
    top_row = int(body.y // TILE)
    bottom_row = int((body.y + body.h - 0.01) // TILE)
    if body.vx > 0:
        col = int((body.x + body.w - 0.01) // TILE)
        if col * TILE >= old_right - 0.01:
            for row in range(top_row, bottom_row + 1):
                if level.is_solid(col, row):
                    body.x = col * TILE - body.w
                    body.vx = 0
                    result["wall"] = 1
                    break
    elif body.vx < 0:
        col = int(body.x // TILE)
        if (col + 1) * TILE <= old_left + 0.01:
            for row in range(top_row, bottom_row + 1):
                if level.is_solid(col, row):
                    body.x = (col + 1) * TILE
                    body.vx = 0
                    result["wall"] = -1
                    break

    # ---- 3 + 4: vertical (solid tiles) ----
    old_top = body.y
    old_bottom = body.y + body.h
    body.y += body.vy * dt
    left_col = int(body.x // TILE)
    right_col = int((body.x + body.w - 0.01) // TILE)
    if body.vy > 0:
        row = int((body.y + body.h - 0.01) // TILE)
        if row * TILE >= old_bottom - 0.01:
            for col in range(left_col, right_col + 1):
                if level.is_solid(col, row):
                    body.y = row * TILE - body.h
                    body.vy = 0
                    result["landed"] = True
                    break
    elif body.vy < 0:
        row = int(body.y // TILE)
        if (row + 1) * TILE <= old_top + 0.01:
            hits = []
            for col in range(left_col, right_col + 1):
                ch = level.tile(col, row)
                if ch in SOLID_CHARS or (finds_hidden and ch == "H"):
                    hits.append((col, row))
            if hits:
                body.y = (row + 1) * TILE
                body.vy = 0
                result["head"] = hits

    # ---- 5: one-way platforms ("=") ----
    if body.vy > 0 and not result["landed"]:
        if land_on_one_way(body, level, old_bottom):
            result["landed"] = True
    return result


def land_on_one_way(body, level, old_bottom):
    """Clouds only stop a body that was ABOVE them and is falling down.
    Jumping up through them from below never bumps the head."""
    row = int((body.y + body.h - 0.01) // TILE)
    if row * TILE < old_bottom - 0.01:
        return False                    # feet were already below the cloud top
    left_col = int(body.x // TILE)
    right_col = int((body.x + body.w - 0.01) // TILE)
    for col in range(left_col, right_col + 1):
        if level.tile(col, row) == "=":
            body.y = row * TILE - body.h
            body.vy = 0
            return True
    return False


