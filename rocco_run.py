def make_window():
    pygame.display.set_caption(GAME_TITLE)
    if IS_WEB:
        # pygbag scales the canvas to fit the browser window (aspect kept)
        return pygame.display.set_mode((SCREEN_W, SCREEN_H))
    try:
        # SCALED + RESIZABLE: drag the window bigger, the game scales with
        # black bars so the 960 x 600 picture keeps its shape
        return pygame.display.set_mode((SCREEN_W, SCREEN_H), pygame.SCALED | pygame.RESIZABLE)
    except Exception:
        return pygame.display.set_mode((SCREEN_W, SCREEN_H))


async def main():
    try:
        pygame.mixer.pre_init(22050, -16, 1, 512)
    except Exception:
        pass
    pygame.init()
    screen = make_window()
    clock = pygame.time.Clock()
    game = Game(screen)
    while game.running:
        dt = min(clock.tick(FPS) / 1000.0, MAX_DT)
        for event in pygame.event.get():
            game.handle_event(event)
        game.update(dt)
        game.draw()
        pygame.display.flip()
        await asyncio.sleep(0)       # lets the browser breathe every frame
    if not IS_WEB:
        pygame.quit()


# Start the game (on the desktop when run from PyCharm, and always in the browser)
if __name__ == "__main__" or IS_WEB:
    asyncio.run(main())
