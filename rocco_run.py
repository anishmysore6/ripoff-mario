class Enemy:
    """kind 'E' = regular walker (stompable), kind 'X' = spiky (not stompable)."""
    def __init__(self, x, y, kind):
        self.kind = kind
        self.x = float(x)
        self.y = float(y)
        self.w = ENEMY_W
        self.h = ENEMY_H
        self.speed = SPIKY_SPEED if kind == "X" else ENEMY_SPEED
        self.vx = -self.speed
        self.vy = 0.0
        self.on_ground = False
        self.active = False         # starts moving once it is on screen
        self.state = "alive"        # alive / squished / knocked
        self.timer = 0.0
        self.anim = random.random() * 10

    def update(self, dt, level):
        self.anim += dt
        if self.state == "squished":
            self.timer -= dt
            return
        if self.state == "knocked":
            self.vy += GRAVITY * dt
            self.x += self.vx * dt
            self.y += self.vy * dt
            return
        if not self.active:
            return
        self.vy = min(self.vy + GRAVITY * dt, MAX_FALL_SPEED)
        result = move_and_collide(self, level, dt)
        self.on_ground = result["landed"]
        if result["wall"] != 0:
            self.vx = -result["wall"] * self.speed   # bumped a wall: turn around
        # turn around at the edge of a platform
        if self.on_ground:
            front_x = self.x + self.w + 2 if self.vx > 0 else self.x - 2
            col = int(front_x // TILE)
            row = int((self.y + self.h + 2) // TILE)
            if not level.can_stand_on(col, row):
                self.vx = -self.vx

    def knock(self, from_x):
        """Knocked out by a bumped block: flips over and falls off the screen."""
        self.state = "knocked"
        self.vy = -450
        self.vx = 120 if self.x + self.w / 2 >= from_x else -120

    def removable(self):
        if self.state == "squished":
            return self.timer <= 0
        return self.y > SCREEN_H + 120


class Mushroom:
    """Rises out of a block, then slides along, falls and bounces off walls."""
    def __init__(self, col, row):
        self.x = col * TILE + (TILE - ITEM_SIZE) / 2
        self.start_y = row * TILE + (TILE - ITEM_SIZE)
        self.y = float(self.start_y)
        self.w = ITEM_SIZE
        self.h = ITEM_SIZE
        self.vx = MUSHROOM_SPEED
        self.vy = 0.0
        self.rising = 0.0          # time spent rising out of the block
        self.state = "rising"
        self.done = False

    def update(self, dt, level):
        if self.state == "rising":
            self.rising += dt
            self.y = self.start_y - min(1.0, self.rising / 0.6) * TILE
            if self.rising >= 0.6:
                self.state = "moving"
            return
        self.vy = min(self.vy + GRAVITY * dt, MAX_FALL_SPEED)
        result = move_and_collide(self, level, dt)
        if result["wall"] != 0:
            self.vx = -result["wall"] * MUSHROOM_SPEED
        if self.y > SCREEN_H + 60:
            self.done = True


