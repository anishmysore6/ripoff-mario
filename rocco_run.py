# HOW TO EDIT THE LEVELS
# ----------------------
# * Each level is a list of EXACTLY 15 text rows. Row 0 is the top of the
#   screen, row 14 is the bottom. All rows of one level must be the same
#   length. Every character is one 40 x 40 tile, so a row of 200
#   characters makes a level 8000 pixels long.
# * Rows 13 and 14 are normally the ground ("#"). The hero stands in row 12.
# * "." is empty air. Any column with no ground in rows 13-14 is a pit.
# * Pipes are 2 tiles wide: the top row of a pipe is "{}" and every row
#   below it is "[]", down to the ground. Example of a 3-tall pipe:
#         {}
#         []
#         []
#        ####
# * "F" is the stone block at the bottom of the flagpole. The pole rises
#   FLAG_POLE_TILES tiles above it. Put it in row 12, on top of the ground.
# * "C" is the bottom-left tile of the castle (5 tiles wide, 5 tall).
#   Put it in row 12 a few tiles after the flag. Leave room to its right.
# * "E", "X", "o", "S" are placed in the air tile where they start.
#
# FAIRNESS RULES (from the professor's build notes, for the default physics)
# * Gaps no wider than 3 tiles.
# * Pipes / walls no taller than 4 tiles.
# * Sky (cloud) platforms at least 7 tiles wide.
# * Height changes between platforms of no more than 2 tiles.
# The game prints a warning in the PyCharm console if a level breaks
# the simple rules (wrong row count, missing S / F / C, gaps too wide...).

