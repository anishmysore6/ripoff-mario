class SoundBank:
    """Makes every sound effect and the music from math. Works silently if
    the computer (or browser) has no audio device."""
    def __init__(self):
        self.ok = False
        self.enabled = True
        self.sounds = {}
        self.music = {}
        self.current_song = None
        self.music_channel = None
        self.rate = 22050
        self.channels = 1
        self.size = -16
        try:
            if not pygame.mixer.get_init():
                pygame.mixer.init(22050, -16, 1, 512)
            self.rate, self.size, self.channels = pygame.mixer.get_init()
            pygame.mixer.set_num_channels(16)
            pygame.mixer.set_reserved(1)
            self.music_channel = pygame.mixer.Channel(0)
            self.build_effects()
            self.ok = True
        except Exception as error:
            print("Sound is off (no audio device?):", error)

    # ---------- raw sample helpers (lists of floats from -1 to 1) ----------
    def tone(self, f0, f1, dur, wave="square", vol=0.3, duty=0.5, decay=1.0):
        n = max(1, int(self.rate * dur))
        out = [0.0] * n
        phase = 0.0
        attack = max(1, int(self.rate * 0.004))
        release = max(1, int(self.rate * 0.02))
        for i in range(n):
            t = i / n
            f = f0 + (f1 - f0) * t
            phase += f / self.rate
            p = phase - int(phase)
            if wave == "square":
                v = 1.0 if p < duty else -1.0
            elif wave == "triangle":
                v = 4.0 * abs(p - 0.5) - 1.0
            elif wave == "sine":
                v = math.sin(6.2831853 * p)
            else:
                v = random.uniform(-1.0, 1.0)
            env = min(1.0, i / attack, (n - i) / release) * ((1.0 - t) ** decay)
            out[i] = v * vol * env
        return out

    def notes(self, freqs, each, wave="square", vol=0.25, duty=0.5):
        out = []
        for f in freqs:
            out += self.tone(f, f, each, wave, vol, duty, decay=0.4)
        return out

    def add(self, a, b):
        if len(a) < len(b):
            a, b = b, a
        out = list(a)
        for i, v in enumerate(b):
            out[i] += v
        return out

    def to_sound(self, samples):
        """Convert float samples to a pygame Sound matching the mixer format."""
        if self.size in (-16, 16):
            data = array.array("h", [int(clamp(v, -1.0, 1.0) * 32000) for v in samples])
        elif self.size == 32:
            data = array.array("f", [clamp(v, -1.0, 1.0) for v in samples])
        elif self.size == -32:
            data = array.array("i", [int(clamp(v, -1.0, 1.0) * 2100000000) for v in samples])
        elif self.size == 8:
            data = array.array("B", [int((clamp(v, -1.0, 1.0) + 1.0) * 127) for v in samples])
        else:
            data = array.array("b", [int(clamp(v, -1.0, 1.0) * 127) for v in samples])
        if self.channels > 1:
            # copy the same samples into every channel (left, right, ...)
            wide = array.array(data.typecode, bytes(len(data) * data.itemsize * self.channels))
            for ch in range(self.channels):
                wide[ch::self.channels] = data
            data = wide
        return pygame.mixer.Sound(buffer=data.tobytes())

    # ---------- sound effects ----------
    def build_effects(self):
        n = note_freq
        fx = {}
        fx["jump"] = self.tone(260, 640, 0.16, "square", 0.22, duty=0.25, decay=0.6)
        fx["coin"] = self.tone(n("B5"), n("B5"), 0.06, "square", 0.2, 0.5, 0.0) + \
            self.tone(n("E6"), n("E6"), 0.26, "square", 0.2, 0.5, 1.2)
        fx["bump"] = self.tone(150, 60, 0.12, "triangle", 0.6, decay=0.5)
        fx["break"] = self.add(self.tone(0, 0, 0.22, "noise", 0.35, decay=1.5),
                               self.tone(220, 50, 0.2, "triangle", 0.5))
        fx["stomp"] = self.tone(520, 110, 0.13, "square", 0.25, duty=0.5, decay=0.4)
        fx["powerup"] = self.notes([n(x) for x in ("C5", "E5", "G5", "C6", "E6", "G6")], 0.06, "square", 0.2, 0.25)
        fx["shrink"] = self.notes([n(x) for x in ("G5", "D5", "B4", "G4")], 0.08, "square", 0.22, 0.5)
        fx["die"] = self.notes([n(x) for x in ("B4", "F5", "F5", "F5", "E5", "D5", "C5", "G4", "C4")], 0.12, "square", 0.22, 0.5)
        fx["clear"] = self.notes([n(x) for x in ("G4", "C5", "E5", "G5", "C6", "E6")], 0.1, "square", 0.22, 0.25) + \
            self.tone(n("G6"), n("G6"), 0.5, "square", 0.2, 0.25, 0.8)
        fx["oneup"] = self.notes([n(x) for x in ("E5", "G5", "E6", "C6", "D6", "G6")], 0.07, "square", 0.2, 0.5)
        fx["tick"] = self.tone(1600, 1600, 0.03, "square", 0.12, decay=0.0)
        fx["pause"] = self.tone(n("E6"), n("E6"), 0.06, "square", 0.18) + self.tone(n("C6"), n("C6"), 0.08, "square", 0.18)
        fx["flag"] = self.tone(1300, 260, 0.9, "sine", 0.3, decay=0.2)
        fx["select"] = self.tone(n("A5"), n("A5"), 0.05, "square", 0.15)
        fx["gameover"] = self.notes([n(x) for x in ("C5", "G4", "E4", "A4", "B4", "A4", "G#4", "A#4", "G#4", "G4")],
                                    0.16, "triangle", 0.4)
        fx["hurry"] = self.notes([n(x) for x in ("E6", "F6", "E6", "F6")], 0.07, "square", 0.15)
        for name, samples in fx.items():
            self.sounds[name] = self.to_sound(samples)

    # ---------- music (built the first time each song is needed) ----------
    def render_song(self, song):
        eighth = song["eighth"]

        def render(text, wave, vol, duty):
            out = []
            for token in text.replace("|", " ").split():
                name, length = token.split(":")
                count = max(1, int(self.rate * eighth * int(length)))
                if name == "R":
                    out += [0.0] * count
                    continue
                period = max(2, int(round(self.rate / note_freq(name))))
                if wave == "square":
                    high = max(1, int(period * duty))
                    cycle = [vol] * high + [-vol] * (period - high)
                else:
                    half = period / 2.0
                    cycle = [vol * (2.0 * abs(i - half) / half - 1.0) for i in range(period)]
                note = (cycle * (count // period + 1))[:count]
                fade = min(count // 2, int(self.rate * 0.02))
                for i in range(fade):
                    note[count - 1 - i] *= i / fade      # short release, no clicks
                out += note
            return out

        lead = render(song["melody"], song["wave"], 0.13, 0.25)
        bass = render(song["bass"], "triangle", 0.2, 0.5)
        length = max(len(lead), len(bass))
        lead += [0.0] * (length - len(lead))
        bass += [0.0] * (length - len(bass))
        return self.to_sound([a + b for a, b in zip(lead, bass)])

    def play(self, name):
        if self.ok and self.enabled and name in self.sounds:
            try:
                self.sounds[name].play()
            except Exception:
                pass

    def play_music(self, theme):
        if not self.ok:
            return
        try:
            if theme not in self.music:
                self.music[theme] = self.render_song(SONGS[theme])
            self.current_song = theme
            self.music_channel.play(self.music[theme], loops=-1)
            if not self.enabled:
                self.music_channel.pause()
        except Exception as error:
            print("Music problem:", error)

    def stop_music(self):
        self.current_song = None
        if self.ok:
            try:
                self.music_channel.stop()
            except Exception:
                pass

    def toggle(self):
        self.enabled = not self.enabled
        if self.ok:
            try:
                if self.enabled:
                    self.music_channel.unpause()
                else:
                    self.music_channel.pause()
            except Exception:
                pass
        return self.enabled


